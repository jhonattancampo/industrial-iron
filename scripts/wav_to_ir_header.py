#!/usr/bin/env python3
"""Convert a WAV IR file to a C++ header with a float array (1024 samples, peak-normalized)."""

import sys
import struct
import wave
import os


IR_LENGTH = 128


def read_wav_samples(path: str) -> tuple[list[float], int]:
    with wave.open(path, "rb") as wf:
        n_channels = wf.getnchannels()
        sampwidth  = wf.getsampwidth()
        n_frames   = wf.getnframes()
        raw        = wf.readframes(n_frames)

    total_samples = n_frames * n_channels
    scale = 2 ** (8 * sampwidth - 1)

    if sampwidth == 3:
        # 24-bit: read 3-byte little-endian signed integers manually
        floats = []
        for i in range(0, len(raw), 3):
            b = raw[i:i + 3]
            val = struct.unpack("<I", b + b"\x00")[0]
            if val >= 0x800000:
                val -= 0x1000000
            floats.append(val / scale)
    else:
        fmt = {1: "b", 2: "h", 4: "i"}
        if sampwidth not in fmt:
            raise ValueError(f"Unsupported sample width: {sampwidth} bytes")
        unpacked = struct.unpack(f"<{total_samples}{fmt[sampwidth]}", raw)
        floats   = [s / scale for s in unpacked]

    # Downmix to mono if stereo
    if n_channels > 1:
        floats = [sum(floats[i:i + n_channels]) / n_channels
                  for i in range(0, len(floats), n_channels)]

    return floats, n_frames


def convert(wav_path: str, header_path: str, array_name: str) -> None:
    samples, n_frames = read_wav_samples(wav_path)

    # Trim or zero-pad to IR_LENGTH
    trimmed = (samples[:IR_LENGTH] + [0.0] * IR_LENGTH)[:IR_LENGTH]

    peak = max(abs(x) for x in trimmed)
    print(f"  {os.path.basename(wav_path)}: {n_frames} frames read, "
          f"trimmed to {IR_LENGTH}, peak before norm = {peak:.6f}")

    if peak > 0.0:
        trimmed = [x / peak for x in trimmed]

    lines = []
    for i in range(0, len(trimmed), 8):
        chunk = trimmed[i:i + 8]
        lines.append("    " + ", ".join(f"{v:.8f}f" for v in chunk) + ",")

    header = f"""\
#pragma once
// Auto-generated by wav_to_ir_header.py — do not edit manually.
// Source: {os.path.basename(wav_path)} | samples: {IR_LENGTH} | peak (pre-norm): {peak:.6f}

static constexpr int k{array_name}_Length = {IR_LENGTH};

static constexpr float k{array_name}[{IR_LENGTH}] = {{
{chr(10).join(lines)}
}};
"""

    with open(header_path, "w") as f:
        f.write(header)

    print(f"  -> wrote {header_path}")


if __name__ == "__main__":
    base_dir  = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    ir_dir    = os.path.join(base_dir, "resources", "ir")
    out_dir   = os.path.join(base_dir, "src", "dsp", "ir")

    files = [
        ("marshall_v30.wav", os.path.join(out_dir, "CabIR_Marshall.h"), "IR_Marshall"),
        ("mesa_v30.wav",     os.path.join(out_dir, "CabIR_Mesa.h"),     "IR_Mesa"),
        ("v30.wav",          os.path.join(out_dir, "CabIR_V30.h"),      "IR_V30"),
    ]

    for wav_name, header_path, array_name in files:
        wav_path = os.path.join(ir_dir, wav_name)
        print(f"Converting {wav_name}...")
        convert(wav_path, header_path, array_name)

    print("Done.")
